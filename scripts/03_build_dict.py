#!/usr/bin/env python3
"""Build the alignment lexicon and the reference pronunciations.

reference.tsv : one 'full' pronunciation per word (every segment kept, θ wherever the
                spelling has z/ce/ci). Taken from the MFA dictionaries; OOV words get one
                from MFA's Spanish G2P.
variants.dict : for every word that occurs in our transcripts, the reference plus variants
                generated BY RULE, so every token has the same options whatever the
                lexicographers happened to list:
                  coda /s/        s | h | ∅
                  onset /s/       s | θ (ceceo) | h
                  θ               θ | s (seseo)
                  ʝ ɟʝ ʎ (onset)  ʝ | ɟʝ | ʃ (sheísmo) | ʎ (only if the reference has ʎ)
                  x               x | h
                  tʃ              tʃ | ʃ
                  final n         n | ŋ | ∅
                  coda ɾ          ɾ | l | ∅        coda l   l | ɾ
                  intervocalic ð  ð | ∅
                Within a word, each process applies uniformly (all coda /s/ of the word
                take the same option) to keep the lexicon small.
No pronunciation probabilities: the aligner picks variants from the audio alone.

usage: 03_build_dict.py <corpus_dir> [<corpus_dir> ...]
"""
import itertools, re, subprocess, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MFA = Path.home() / "Documents/MFA/pretrained_models/dictionary"
OUT = ROOT / "corpus"
NASAL = {"ã": "a", "ẽ": "e", "ĩ": "i", "õ": "o", "ũ": "u"}
VOWELS = set("aeiou")
VOICED_C = {"b", "β", "d̪", "ð", "ɡ", "ɣ", "m", "n", "ɲ", "l", "ɾ", "r", "ʝ", "ɟʝ"}
sys.path.insert(0, str(Path(__file__).parent))


def read(name):
    d = defaultdict(list)
    for line in open(MFA / f"{name}.dict", encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) >= 2:
            d[parts[0]].append((float(parts[1]) if len(parts) > 2 else 1.0, tuple(parts[-1].split())))
    return d


def reference(prons):
    oral = lambda ph: tuple(NASAL.get(x, x) for x in ph)
    # most θ, longest, fewest h/ʃ/ʎ-for-l, most probable
    best = max(prons, key=lambda pp: (pp[1].count("θ"), len(pp[1]),
                                      -sum(x in ("h", "ʃ") for x in pp[1]), pp[0]))
    return oral(best[1])


def coda_flags(ph):
    from importlib import import_module
    syl, coda, _ = import_module("04_features").syllabify(list(ph))
    return coda


def variants(ref, word):
    """Rule-generated pronunciation variants of a reference pronunciation."""
    coda = coda_flags(ref)
    n = len(ref)
    sites = defaultdict(list)          # process -> positions
    for i, p in enumerate(ref):
        nxt = ref[i + 1] if i + 1 < n else None
        prv = ref[i - 1] if i else None
        if p == "s" and coda[i]:
            sites["s_coda"].append(i)
        elif p == "s":
            sites["s_onset"].append(i)
        elif p == "θ":
            sites["theta"].append(i)
        elif p in ("ʝ", "ɟʝ", "ʎ") and not coda[i]:
            sites["y"].append(i)
        elif p == "x":
            sites["x"].append(i)
        elif p == "tʃ":
            sites["ch"].append(i)
        elif p == "n" and i == n - 1:
            sites["n_final"].append(i)
        elif p == "ɾ" and coda[i]:
            sites["r_coda"].append(i)
        elif p == "l" and coda[i]:
            sites["l_coda"].append(i)
        elif p == "ð" and prv in VOWELS and nxt in VOWELS:
            sites["d_intervoc"].append(i)
    has_ll = "ʎ" in ref or "ll" in word
    options = {
        "s_coda": [None, "h", ""],
        "s_onset": [None, "θ", "h"],
        "theta": [None, "s"],
        "y": [None, "ʝ", "ɟʝ", "ʃ"] + (["ʎ"] if has_ll else []),
        "x": [None, "h"],
        "ch": [None, "ʃ"],
        "n_final": [None, "ŋ", ""],
        "r_coda": [None, "l", ""],
        "l_coda": [None, "ɾ"],
        "d_intervoc": [None, ""],
    }
    procs = list(sites)
    out = set()
    for combo in itertools.product(*[options[p] for p in procs]):
        ph = list(ref)
        for proc, opt in zip(procs, combo):
            if opt is None:
                continue
            for i in sites[proc]:
                ph[i] = opt
        # voiced allophone of coda s before voiced consonant
        ph2 = [x for x in ph if x != ""]
        out.add(tuple(ph2))
    return out


def corpus_words(dirs):
    words = set()
    for d in dirs:
        for lab in Path(d).rglob("*.lab"):
            for w in re.findall(r"[a-záéíóúüñ]+(?:'[a-z]+)?", lab.read_text(encoding="utf-8").lower()):
                words.add(w)
    return words


def main():
    dirs = sys.argv[1:]
    dicts = [read(n) for n in ("spanish_mfa", "spanish_latin_america_mfa", "spanish_spain_mfa")]
    allprons = defaultdict(list)
    for d in dicts:
        for w, pp in d.items():
            allprons[w] += pp
    refs = {w: reference(pp) for w, pp in allprons.items()}

    words = corpus_words(dirs)
    # G2P results are cached (17 Oct 2026): every batch used to redo the G2P of every unknown word of every corpus
    cache = OUT / "g2p_cache.tsv"
    cached = {}
    if cache.exists():
        for line in open(cache, encoding="utf-8"):
            parts = line.rstrip("\n").split("\t")
            if len(parts) == 2 and parts[1].strip():
                cached[parts[0]] = tuple(parts[1].split())
    for w in words:
        if w not in refs and w in cached:
            refs[w] = cached[w]
    oov = sorted(w for w in words if w not in refs)
    print(f"{len(words)} corpus words, {len(oov)} OOV not in the cache ({len(cached)} cached)")
    if oov:   # G2P for out-of-vocabulary words (names, rare words, whisper spellings)
        import os
        tmp_in, tmp_out = OUT / f"oov_{os.getpid()}.txt", OUT / f"oov_{os.getpid()}.dict"
        tmp_in.write_text("\n".join(oov), encoding="utf-8")
        mfa = Path(sys.executable).parent / "mfa"
        subprocess.run([str(mfa), "model", "download", "g2p", "spanish_latin_america_mfa"],
                       capture_output=True)
        subprocess.run([str(mfa), "g2p", str(tmp_in), "spanish_latin_america_mfa", str(tmp_out),
                        "--num_pronunciations", "1"], capture_output=True)
        if tmp_out.exists():
            for line in open(tmp_out, encoding="utf-8"):
                parts = line.rstrip("\n").split("\t")
                if len(parts) >= 2 and parts[-1].strip():
                    refs[parts[0]] = tuple(NASAL.get(x, x) for x in parts[-1].split())
            with open(cache, "a", encoding="utf-8") as fc:
                for w in oov:
                    if w in refs:
                        fc.write(f"{w}\t{' '.join(refs[w])}\n")

    nv = 0
    with open(OUT / "variants.dict", "w", encoding="utf-8") as fv, \
         open(OUT / "reference.tsv", "w", encoding="utf-8") as fr:
        for w in sorted(refs):
            fr.write(f"{w}\t{' '.join(refs[w])}\n")
        for w in sorted(words):
            if w not in refs:
                continue
            for ph in sorted(variants(refs[w], w)):
                if ph:
                    fv.write(f"{w}\t{' '.join(ph)}\n"); nv += 1
    print(f"lexicon: {len(words)} words, {nv} pronunciations ({nv / max(1, len(words)):.1f} per word)")


if __name__ == "__main__":
    main()
